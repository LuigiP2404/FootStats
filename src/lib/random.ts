// Tiny seeded PRNG (mulberry32): the same seed always produces the same sequence.
// Used by the mocks so generated data is stable across requests and server instances.
export function seededRandom(seed: number) {
    let a = seed;
    return () => {
        a = (a + 0x6d2b79f5) | 0;
        let t = Math.imul(a ^ (a >>> 15), 1 | a);
        t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
        return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
    };
}
